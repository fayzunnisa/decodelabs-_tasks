import glob
import pandas as pd
import matplotlib.pyplot as plt

file = glob.glob("/content/*.xlsx")[0]
df = pd.read_excel(file)
df["Date"] = pd.to_datetime(df["Date"])

# Chart 1: order status
s = df["OrderStatus"].value_counts()
cols = ["#d9534f" if k in ("Cancelled", "Returned") else "#b0b0b0" for k in s.index]
fig, ax = plt.subplots(figsize=(7, 4))
ax.barh(s.index, s.values, color=cols)
ax.invert_yaxis()
ax.bar_label(ax.containers[0], padding=3)
ax.set_title("41% of orders were cancelled or returned", loc="left", fontweight="bold")
ax.spines[["top", "right"]].set_visible(False)
fig.savefig("chart1.png", dpi=200, bbox_inches="tight")
plt.show()

# Chart 2: delivered revenue by product
d = df[df["OrderStatus"] == "Delivered"].groupby("Product")["TotalPrice"].sum().sort_values()
cols = ["#1f77b4" if v == d.max() else "#b0b0b0" for v in d.values]
fig, ax = plt.subplots(figsize=(7, 4))
ax.barh(d.index, d.values, color=cols)
ax.bar_label(ax.containers[0], fmt="%.0f", padding=3)
ax.set_title("Laptop leads delivered revenue; Desk trails", loc="left", fontweight="bold")
ax.spines[["top", "right"]].set_visible(False)
fig.savefig("chart2.png", dpi=200, bbox_inches="tight")
plt.show()

# Chart 3: first-half revenue by year
h1 = df[df["Date"].dt.month <= 6].groupby(df["Date"].dt.year)["TotalPrice"].sum()
fig, ax = plt.subplots(figsize=(7, 4))
ax.plot(h1.index, h1.values, marker="o", color="#d9534f")
for x, y in zip(h1.index, h1.values):
    ax.annotate(f"{y/1000:.0f}k", (x, y), textcoords="offset points", xytext=(0, 8), ha="center")
    ax.set_ylim(0, h1.max() * 1.2)
    ax.set_xticks(list(h1.index))
    ax.set_title("First-half revenue fell about 10% every year", loc="left", fontweight="bold")
    ax.spines[["top", "right"]].set_visible(False)
    fig.text(0.01, -0.02, "Jan to Jun of each year. Includes cancelled and returned orders.", fontsize=8)
    fig.savefig("chart3.png", dpi=200, bbox_inches="tight")
    plt.show()